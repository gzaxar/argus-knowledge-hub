def _sim(m: dict) -> str:
    cast = {"float": "float", "int": "int", "bool": "int", "enum": "int", "string": "str"}
    state = ",\n".join(f"    {p['name']!r}: {p['sim']!r}" for p in m["parameters"].values())
    reads = ",\n".join(f"    {p['read']!r}: ({(p['sim_from'] or p['name'])!r}, {p['reply']!r})"
                       for p in m["parameters"].values() if p["read"])
    writes = ",\n".join(f"    (re.compile({_sim_regex(p['write'])!r}), {p['name']!r}, {cast[p['type']]}, {p['ack']!r})"
                        for p in m["parameters"].values() if p["write"])
    term = "".join({"CR": "\r", "LF": "\n"}[t] for t in m["terminator"]) or "\n"
    return f'''#!/usr/bin/env python3
"""A simulator of {m['description']}: answers, over TCP, the commands the IOC sends.

{HEADER_NOTE}
It keeps one value per quantity: a query answers it, a setting changes it. Edit STATE or answer() to make it
behave more like the device (ramps, interlocks, errors).

    python3 sim/{m['app']}_sim.py --port {m['port']}
"""
import argparse
import re
import socketserver

TERMINATOR = {term.encode()!r}

STATE = {{
{state}
}}

# query -> (quantity, reply format)
READS = {{
{reads}
}}

# (command pattern, quantity, type, acknowledgement)
WRITES = [
{writes}
]


def answer(line):
    """The device's reply to one command, or None when it sends none."""
    if line in READS:
        name, fmt = READS[line]
        return fmt % STATE[name]
    for pattern, name, kind, ack in WRITES:
        match = pattern.match(line)
        if match:
            try:
                STATE[name] = kind(float(match.group(1))) if kind is int else kind(match.group(1))
            except ValueError:
                return ack and "ERR"
            return ack
    print(f"unknown command {{line!r}}")
    return None


class Handler(socketserver.BaseRequestHandler):
    def handle(self):
        buffer = b""
        while True:
            data = self.request.recv(1024)
            if not data:
                return
            buffer += data
            while TERMINATOR in buffer:
                raw, buffer = buffer.split(TERMINATOR, 1)
                reply = answer(raw.decode(errors="replace").strip())
                if reply is not None:
                    self.request.sendall(reply.encode() + TERMINATOR)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default={m['port']})
    args = parser.parse_args()
    socketserver.ThreadingTCPServer.allow_reuse_address = True
    with socketserver.ThreadingTCPServer((args.host, args.port), Handler) as server:
        print(f"{m['app']} simulator on {{args.host}}:{{args.port}}")
        server.serve_forever()


if __name__ == "__main__":
    main()
'''


