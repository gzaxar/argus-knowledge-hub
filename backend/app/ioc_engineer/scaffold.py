"""A new EPICS support module, written from a description of the device, in the house style of ppt-modulator.

A driver repository at INFN is a makeBaseApp tree that builds a support library and an example IOC, with a
simulator to run it on a laptop, and two small files elsewhere that make it an ibek module (ibek-support-infn)
and a template the beamlines use (ibek-templates). From one description — what the device is called, how it is
reached, the quantities it reads and sets (each with its command), and the sequences an operator would otherwise
step through by hand — this writes all of it:

    <name>/configure/…, Makefile                 makeBaseApp top, RELEASE naming asyn, StreamDevice, sequencer
    <name>/<app>App/src/Makefile                 <app>Support library (driver + state programs) and the <app> IOC
    <name>/<app>App/src/<app>Driver.{h,cpp}      an asynPortDriver: polls the readbacks, sends setpoints (driver: asyn)
    <name>/<app>App/src/<app><Seq>.st            one SNL state program per sequence: step, wait, retry, abort
    <name>/<app>App/Db/<app>.proto               a StreamDevice protocol per command (driver: stream)
    <name>/<app>App/Db/<app>.template            _RB and _SP records per quantity, and a template per sequence
    <name>/iocBoot/ioc<app>/st.cmd, st-sim.cmd   the bench IOC, against the device or the simulator
    <name>/sim/<app>_sim.py                      a TCP simulator answering the same commands
    ibek-support-infn/<name>/…                   install.yml and ibek.support.yaml (one controller entity)
    ibek-templates/…                             the template and a fixture, rendered against each other

The ibek files are checked the way every draft here is (the fixture rendered with the template and validated
against the entity models just written). The C++ and SNL are not compiled here: ARGUS has no EPICS toolchain,
and says so; `make` in the devcontainer (ghcr.io/infn-epics/infn-epics-ioc-base) and the simulator are the next
step. The description is checked first: names that become PVs, C identifiers and protocol names, one conversion
in each command, sequence steps that name quantities that can be set and read.
"""
from __future__ import annotations

import math
import re
from collections import OrderedDict
from typing import Any, Optional

import yaml

TYPES = {"float", "int", "bool", "enum", "string"}
NAME = re.compile(r"[A-Za-z][A-Za-z0-9]{0,23}")
REPO = re.compile(r"[a-z0-9][a-z0-9._-]{0,63}")
CONV = re.compile(r"%(?!%)[-+ 0#]*\d*(?:\.\d+)?([a-zA-Z])")
LETTERS = {"float": "feg", "int": "diux", "bool": "diux", "enum": "diux", "string": "s"}
DEFAULT_REPLY = {"float": "%f", "int": "%d", "bool": "%d", "enum": "%d", "string": "%s"}
SCANS = [0.1, 0.2, 0.5, 1, 2, 5, 10]
MBB = ["ZR", "ON", "TW", "TH", "FR", "FV", "SX", "SV", "EI", "NI", "TE", "EL", "TV", "TT", "FT", "FF"]
TERMINATORS = {"crlf": ["CR", "LF"], "lf": ["LF"], "cr": ["CR"], "none": []}
OPS = {"equals": "==", "above": ">", "below": "<"}
HEADER_NOTE = "Generated by the ARGUS IOC engineer (ioc_scaffold_module) from the module's description."


PV_PART = re.compile(r"[A-Za-z0-9_:.-]{1,60}")
HOST = re.compile(r"[A-Za-z0-9.-]{1,253}")
TTY = re.compile(r"/dev/[A-Za-z0-9_./-]{1,60}")


def _text(value: Any, default: str, limit: int = 120) -> str:
    """Free text that ends up in C, SNL and protocol comments, db DESC fields and st.cmd: one line, no quotes,
    nothing that closes a comment."""
    t = " ".join(str(value if value is not None else default).split())
    return (t.replace("*/", "* /").replace('"', "'").replace("\\", "/") or default)[:limit]


class Invalid(ValueError):
    """The description cannot become a module as it stands; every reason goes back together."""


# --- the description -------------------------------------------------------------------------------------------

def _terminator(value: Any) -> list[str]:
    raw = str("crlf" if value is None else value).strip()
    key = (raw.lower().replace("\\r", "cr").replace("\\n", "lf").replace("\r", "cr").replace("\n", "lf")
           .replace(" ", "").replace("+", ""))
    if key in TERMINATORS:
        return TERMINATORS[key]
    raise Invalid([f"terminator {value!r}: one of CRLF, LF, CR, none"])


def _command(text: Any, where: str, problems: list) -> Optional[str]:
    if text is None:
        return None
    s = str(text)
    if not s or any(not (32 <= ord(c) < 127) for c in s) or "\\" in s:
        problems.append(f"{where}: {s!r} must be printable ASCII, without backslashes (the terminator is added)")
        return None
    return s


def _conversions(fmt: str) -> list[str]:
    return CONV.findall(fmt)


def normalize(spec: Any) -> dict:
    """The description, checked and with its defaults filled in; Invalid lists everything wrong at once."""
    if isinstance(spec, str):
        try:
            spec = yaml.safe_load(spec)
        except yaml.YAMLError as e:
            raise Invalid([f"the description is not valid YAML: {e}"])
    if not isinstance(spec, dict):
        raise Invalid(["the description is a mapping: name, app, driver, transport, parameters, sequences"])
    p: list = []
    name = str(spec.get("name") or "").strip()
    if not REPO.fullmatch(name):
        p.append(f"name {name!r}: the repository name, lower case (letters, digits, - _ .)")
    app = str(spec.get("app") or re.sub(r"[^A-Za-z0-9]", "", name.split("-")[-1] if name else "")).strip()
    if not NAME.fullmatch(app or "-"):
        p.append(f"app {app!r}: the App prefix (<app>App, <app>Support, the <app> IOC), letters and digits")
    driver = str(spec.get("driver") or "stream").lower()
    if driver not in ("stream", "asyn"):
        p.append(f"driver {driver!r}: stream (StreamDevice protocol) or asyn (a C++ asynPortDriver)")
    transport = str(spec.get("transport") or "ip").lower()
    if transport not in ("ip", "serial"):
        p.append(f"transport {transport!r}: ip or serial")
    try:
        term = _terminator(spec.get("terminator"))
    except Invalid as e:
        p += e.args[0]
        term = TERMINATORS["crlf"]
    try:
        poll = float(spec.get("poll", 1.0))
        timeout = float(spec.get("timeout", 1.0))
        if poll <= 0 or timeout <= 0:
            raise ValueError
    except (TypeError, ValueError):
        p.append("poll and timeout are seconds, greater than zero")
        poll, timeout = 1.0, 1.0

    params: "OrderedDict[str, dict]" = OrderedDict()
    for i, raw in enumerate(spec.get("parameters") or []):
        if not isinstance(raw, dict):
            p.append(f"parameters[{i}] is a mapping (name, type, read, write…)")
            continue
        pn = str(raw.get("name") or "")
        where = f"parameter {pn or i}"
        if not NAME.fullmatch(pn):
            p.append(f"{where}: name must be letters and digits, starting with a letter, at most 24")
            continue
        if pn.lower() in (x.lower() for x in params) or pn.lower() == "connected":
            p.append(f"{where}: the name is taken")
            continue
        kind = str(raw.get("type") or "float").lower()
        if kind not in TYPES:
            p.append(f"{where}: type {kind!r} is one of {', '.join(sorted(TYPES))}")
            continue
        read = _command(raw.get("read"), f"{where}.read", p)
        write = _command(raw.get("write"), f"{where}.write", p)
        reply = _command(raw.get("reply") or DEFAULT_REPLY[kind], f"{where}.reply", p) if read else None
        ack = _command(raw.get("ack"), f"{where}.ack", p) if write else None
        if not read and not write:
            p.append(f"{where}: give a read command, a write command, or both")
        if read is not None and _conversions(read):
            p.append(f"{where}.read: a query has no % conversion (write %% for a literal %)")
        for label, fmt in (("reply", reply), ("write", write)):
            if fmt is None:
                continue
            letters = _conversions(fmt)
            if len(letters) != 1 or letters[0] not in LETTERS[kind]:
                p.append(f"{where}.{label} {fmt!r}: exactly one conversion, %{LETTERS[kind][0]} for a {kind}")
        states = [str(s) for s in (raw.get("states") or (["Off", "On"] if kind == "bool" else []))]
        if kind == "bool" and len(states) != 2:
            p.append(f"{where}: a bool has two states (the names for 0 and 1)")
        if kind == "enum" and not 2 <= len(states) <= 16:
            p.append(f"{where}: an enum has 2 to 16 states")
        if any(len(s) > 25 or '"' in s for s in states):
            p.append(f"{where}: state names are at most 25 characters, without quotes")
        limits = raw.get("limits")
        if limits is not None and not (isinstance(limits, (list, tuple)) and len(limits) == 2
                                       and all(isinstance(x, (int, float)) for x in limits)):
            p.append(f"{where}.limits: [low, high]")
            limits = None
        try:
            sim = raw.get("sim", "" if kind == "string" else 0)
            sim = {"float": float, "int": int, "bool": int, "enum": int, "string": str}[kind](sim)
        except (TypeError, ValueError):
            p.append(f"{where}.sim: the simulator's starting value, a {kind}")
            sim = 0
        sim_from = raw.get("sim_from")
        params[pn] = {"name": pn, "type": kind, "read": read, "reply": reply, "write": write, "ack": ack,
                      "sim_from": str(sim_from) if sim_from is not None else None,
                      "unit": _text(raw.get("unit"), "", 15), "prec": int(raw.get("prec", 3)),
                      "states": states, "limits": limits, "sim": sim,
                      "description": _text(raw.get("description"), pn, 40)}
    if not params:
        p.append("parameters: at least one quantity the device reads or sets")
    for q in params.values():
        if q["sim_from"] is not None and (q["sim_from"] not in params or q["sim_from"] == q["name"]
                                          or params[q["sim_from"]]["type"] != q["type"]):
            p.append(f"parameter {q['name']}.sim_from: another parameter of the same type, whose simulated "
                     "value this query reports")

    seqs: "OrderedDict[str, dict]" = OrderedDict()
    for i, raw in enumerate(spec.get("sequences") or []):
        if not isinstance(raw, dict):
            p.append(f"sequences[{i}] is a mapping (name, steps)")
            continue
        sn = str(raw.get("name") or "")
        where = f"sequence {sn or i}"
        if not NAME.fullmatch(sn) or sn in params or sn in seqs:
            p.append(f"{where}: a name of letters and digits, not a parameter's or another sequence's")
            continue
        steps = []
        for j, st in enumerate(raw.get("steps") or []):
            w = f"{where}.steps[{j + 1}]"
            if not isinstance(st, dict):
                p.append(f"{w}: a mapping (set, value, wait, equals|above|below, timeout)")
                continue
            step = {"set": None, "value": None, "wait": None, "op": None, "target": None,
                    "timeout": float(st.get("timeout", 30)), "delay": float(st.get("delay", 1.0))}
            if st.get("set") is not None:
                target = params.get(str(st["set"]))
                if not target or not target["write"] or target["type"] == "string":
                    p.append(f"{w}: set {st['set']!r} is not a numeric parameter with a write command")
                else:
                    step["set"] = target["name"]
                    step["value"] = _number(target, st.get("value"), f"{w}.value", p)
            if st.get("wait") is not None:
                target = params.get(str(st["wait"]))
                ops = [k for k in OPS if k in st]
                if not target or not target["read"] or target["type"] == "string":
                    p.append(f"{w}: wait {st['wait']!r} is not a numeric parameter with a read command")
                elif len(ops) != 1:
                    p.append(f"{w}: wait needs one of equals, above, below")
                else:
                    step["wait"], step["op"] = target["name"], OPS[ops[0]]
                    step["target"] = _number(target, st[ops[0]], f"{w}.{ops[0]}", p)
            if not step["set"] and not step["wait"]:
                p.append(f"{w}: a step sets a parameter, waits for one, or both")
            steps.append(step)
        if not steps:
            p.append(f"{where}: at least one step")
        seqs[sn] = {"name": sn, "steps": steps, "description": _text(raw.get("description"), sn),
                    "retry_delay": float(raw.get("retry_delay", 5.0))}
    from app.ioc_engineer.tools import GROUPS
    group = str(spec.get("group") or "io")
    if group not in GROUPS:
        p.append(f"group {group!r}: one of {', '.join(GROUPS)}")
    folder = str(spec.get("folder") or name)
    if not REPO.fullmatch(folder):
        p.append(f"folder {folder!r}: the ibek-support-infn directory, like name")
    for key, pattern, what in (("prefix", PV_PART, "a PV prefix"), ("device", PV_PART, "a PV part"),
                               ("ip", HOST, "a host name or address"), ("tty", TTY, "a /dev/ path")):
        if spec.get(key) is not None and not pattern.fullmatch(str(spec[key])):
            p.append(f"{key} {spec[key]!r}: {what}")
    for key in ("port", "baud"):
        if spec.get(key) is not None and not (isinstance(spec[key], int) and 0 < spec[key] < 10_000_000):
            p.append(f"{key} {spec[key]!r}: a positive integer")
    version = str(spec.get("version") or "main")
    if not re.fullmatch(r"[A-Za-z0-9._/-]{1,100}", version):
        p.append(f"version {version!r}: a tag or branch")
    organization = str(spec.get("organization") or "https://github.com/infn-epics/").rstrip("/") + "/"
    if not re.fullmatch(r"https://[A-Za-z0-9.-]+/[\w.-]+(/[\w.-]+)*/", organization):
        p.append(f"organization {organization!r}: an https URL, like https://github.com/infn-epics/")
    if p:
        raise Invalid(p)
    return {
        "name": name, "app": app, "Class": app[0].upper() + app[1:] + "Driver", "driver": driver,
        "transport": transport, "terminator": term, "poll": poll, "timeout": timeout,
        "ip": str(spec.get("ip") or "127.0.0.1"), "port": int(spec.get("port") or 4001),
        "tty": str(spec.get("tty") or "/dev/ttyUSB0"), "baud": int(spec.get("baud") or 9600),
        "description": _text(spec.get("description"), f"{app} device"),
        "organization": organization, "version": version, "group": group,
        "devtype": re.sub(r"[^A-Za-z0-9_.-]", "", str(spec.get("devtype") or app.lower())) or app.lower(),
        "folder": folder,
        "prefix": str(spec.get("prefix") or f"TEST:{group.upper()}:{app.upper()}"),
        "device": str(spec.get("device") or f"{app.upper()}01"),
        "parameters": params, "sequences": seqs,
    }


def _number(param: dict, value: Any, where: str, problems: list) -> Optional[float]:
    """A value a step sets or waits for: a number, or the name of one of the parameter's states."""
    if isinstance(value, str) and value in param["states"]:
        return float(param["states"].index(value))
    if isinstance(value, bool):
        return float(value)
    try:
        return float(value)
    except (TypeError, ValueError):
        names = f" or one of {', '.join(param['states'])}" if param["states"] else ""
        problems.append(f"{where}: {value!r} is not a number{names}")
        return None


# --- small helpers ---------------------------------------------------------------------------------------------

def _c(text: str) -> str:
    """A C (and iocsh, and StreamDevice) string literal for a checked command: only the quote needs escaping."""
    return '"' + text.replace('"', '\\"') + '"'


def _scanf(fmt: str, kind: str) -> str:
    """The reply format as sscanf reads it: no precision, a double for floats, a bounded string."""
    out = {"float": "%lf", "string": "%255s"}.get(kind)
    return CONV.sub(lambda m: out or "%" + ("d" if m.group(1) in "di" else m.group(1)), fmt)


def _num(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else repr(float(v))


def _scan(poll: float) -> str:
    best = min(SCANS, key=lambda s: abs(math.log(s) - math.log(poll)))
    return (f"{best:g}" if best >= 1 else f"{best:g}".lstrip("0")) + " second"


def _eos(term: list) -> str:
    return "".join({"CR": "\\r", "LF": "\\n"}[t] for t in term)


def _pv(param: dict, side: str) -> str:
    return f"{param['name']}_{side}"


def _sim_regex(fmt: str) -> str:
    parts, last = [], 0
    for m in CONV.finditer(fmt):
        parts.append(re.escape(fmt[last:m.start()].replace("%%", "%")))
        parts.append(r"\s*(\S+?)" if m.group(1) != "s" else r"(.*?)")
        last = m.end()
    parts.append(re.escape(fmt[last:].replace("%%", "%")))
    return "^" + "".join(parts) + "$"


