def _records(m: dict) -> list:
    out = []
    if m["driver"] == "asyn":
        out.append({"pv": "$(P):$(R):Connected", "record": "bi", "what": "the device answers the poll"})
    for p in m["parameters"].values():
        for side, cmd in (("RB", p["read"]), ("SP", p["write"])):
            if cmd:
                rtype = {"float": "ai/ao", "int": "longin/longout", "bool": "bi/bo", "enum": "mbbi/mbbo",
                         "string": "lsi/lso"}[p["type"]].split("/")[0 if side == "RB" else 1]
                unit = f" [{p['unit']}]" if p["unit"] else ""
                out.append({"pv": f"$(P):$(R):{_pv(p, side)}", "record": rtype,
                            "what": f"{p['description']}{unit}: `{cmd}`"})
    for s in m["sequences"]:
        for suffix, rtype, what in (("Start", "bo", "start"), ("Abort", "bo", "abort"),
                                    ("State", "mbbi", "Idle/Running/Done/Failed/Aborted"),
                                    ("Step", "longin", "current step"), ("Message", "stringin", "what it is doing")):
            out.append({"pv": f"$(P):$(R):{s}:{suffix}", "record": rtype, "what": f"{s}: {what}"})
    return out


