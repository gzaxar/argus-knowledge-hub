def _proto(m: dict) -> str:
    term = " ".join(m["terminator"]) or '""'
    lines = [f"# {m['app']}.proto - StreamDevice protocol for {m['description']}", f"# {HEADER_NOTE}",
             "# One protocol per command; the records are in " + m["app"] + ".template.", "",
             f"Terminator = {term};", f"ReplyTimeout = {int(m['timeout'] * 1000)};", "ReadTimeout = 100;",
             "LockTimeout = 5000;", ""]
    for p in m["parameters"].values():
        if p["read"]:
            # %#s: the whole reply, spaces included, as the asyn driver reads a plain %s.
            reply = "%#s" if p["type"] == "string" and p["reply"] == "%s" else p["reply"]
            lines.append(f"get_{p['name']} {{ out {_c(p['read'])}; in {_c(reply)}; }}")
        if p["write"]:
            ack = f" in {_c(p['ack'])};" if p["ack"] else ""
            lines.append(f"set_{p['name']} {{ out {_c(p['write'])};{ack} }}")
    return "\n".join(lines) + "\n"


