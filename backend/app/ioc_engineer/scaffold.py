def _msg(text: str) -> str:
    return text[:39].replace('"', "'")


def _step_text(step: dict) -> str:
    parts = []
    if step["set"]:
        parts.append(f"{step['set']}_SP={_num(step['value'])}")
    if step["wait"]:
        parts.append(f"{step['wait']}_RB{step['op']}{_num(step['target'])}")
    return ", ".join(parts)


def _snl(m: dict, s: dict) -> str:
    a, n, steps = m["app"], s["name"], s["steps"]
    prog = f"{a}{n}"
    sets = OrderedDict((st["set"], None) for st in steps if st["set"])
    waits = OrderedDict((st["wait"], None) for st in steps if st["wait"])
    doc = []
    for i, st in enumerate(steps, 1):
        what = []
        if st["set"]:
            what.append(f"set {st['set']}_SP to {_num(st['value'])}")
        if st["wait"]:
            what.append(f"wait until {st['wait']}_RB {st['op']} {_num(st['target'])} ({_num(st['timeout'])} s)")
        else:
            what.append(f"wait {_num(st['delay'])} s")
        doc.append(f" *   {i}. " + ", then ".join(what))
    decl = []
    for name in sets:
        decl += [f"double sp_{name};", f'assign sp_{name} to "{{P}}:{{R}}:{name}_SP";', ""]
    for name in waits:
        decl += [f"double rb_{name};", f'assign rb_{name} to "{{P}}:{{R}}:{name}_RB";', f"monitor rb_{name};", ""]

    def enter(i: int) -> list:
        """What the transition into step i does: count the tries, send the step's command."""
        st = steps[i - 1]
        out = ["tries = 1;", f"maxTries = (int)({_num(st['timeout'])} / retryDelay) + 1;"]
        if st["set"]:
            out += [f"sp_{st['set']} = {_num(st['value'])};", f"pvPut(sp_{st['set']});"]
        return out

    def block(lines: list, indent: int) -> str:
        return "\n".join(" " * indent + x for x in lines)

    states = []
    for i, st in enumerate(steps, 1):
        nxt = f"step{i + 1}" if i < len(steps) else "done"
        go = enter(i + 1) if i < len(steps) else []
        label = _msg(f"{i}: {_step_text(st)}")
        when = []
        if st["wait"]:
            cond = f"rb_{st['wait']} {st['op']} {_num(st['target'])}"
            when.append(f"        when ({cond}) {{\n{block(go, 12)}\n        }} state {nxt}")
            resend = [f"pvPut(sp_{st['set']});"] if st["set"] else []
            when.append(f"        when (delay(retryDelay) && tries < maxTries) {{\n{block(['tries++;'] + resend, 12)}"
                        f"\n        }} state step{i}")
            fail = _msg(f"{i}: timeout, {st['wait']}_RB={'%g'}")
            when.append(f"        when (delay(retryDelay)) {{\n"
                        f"            sprintf(message, \"{fail}\", rb_{st['wait']});\n"
                        f"            pvPut(message);\n        }} state failed")
        else:
            when.append(f"        when (delay({_num(st['delay'])})) {{\n{block(go, 12)}\n        }} state {nxt}")
        states.append(f"""    /* Step {i}: {_step_text(st)} */
    state step{i} {{
        entry {{
            seqState = 1;
            pvPut(seqState);
            seqStep = {i};
            pvPut(seqStep);
            strcpy(message, "{label}");
            pvPut(message);
        }}
        when (abortCmd) {{
        }} state aborted
{chr(10).join(when)}
    }}""")
    finals = []
    for name, value, text in (("done", 2, "Done"), ("failed", 3, None), ("aborted", 4, "Aborted")):
        msg = f'\n            strcpy(message, "{text}");\n            pvPut(message);' if text else ""
        reset = "\n            abortCmd = 0;\n            pvPut(abortCmd);" if name == "aborted" else ""
        finals.append(f"""    state {name} {{
        entry {{
            seqState = {value};
            pvPut(seqState);{msg}{reset}
        }}
        when () {{
        }} state idle
    }}""")
    return f"""/*
 * {prog}.st - {s['description']}
 *
 * {HEADER_NOTE}
 *
 * Steps:
{chr(10).join(doc)}
 *
 * $(P):$(R):{n}:Start = 1 starts it; $(P):$(R):{n}:Abort = 1 stops it at the current step. A step's command is
 * sent again every RETRY_DELAY seconds until its condition holds; after the step's timeout the program stops in
 * Failed, with the value it last read in $(P):$(R):{n}:Message.
 */
program {prog}("P={m['prefix']},R={m['device']},RETRY_DELAY={_num(s['retry_delay'])}")

option +r;

%%#include <stdio.h>
%%#include <stdlib.h>
%%#include <string.h>

%{{
static double macDouble(const char *text, double fallback)
{{
    double value = (text && *text) ? atof(text) : 0.0;
    return value > 0.0 ? value : fallback;
}}
}}%

double retryDelay;
int tries;
int maxTries;

int startCmd;
assign startCmd to "{{P}}:{{R}}:{n}:Start";
monitor startCmd;

int abortCmd;
assign abortCmd to "{{P}}:{{R}}:{n}:Abort";
monitor abortCmd;

int seqState;
assign seqState to "{{P}}:{{R}}:{n}:State";

int seqStep;
assign seqStep to "{{P}}:{{R}}:{n}:Step";

string message;
assign message to "{{P}}:{{R}}:{n}:Message";

{chr(10).join(decl)}
ss {prog} {{

    state init {{
        when () {{
            retryDelay = macDouble(macValueGet("RETRY_DELAY"), {_num(s['retry_delay'])});
            seqState = 0;
            pvPut(seqState);
            seqStep = 0;
            pvPut(seqStep);
        }} state idle
    }}

    state idle {{
        when (startCmd) {{
            startCmd = 0;
            pvPut(startCmd);
            abortCmd = 0;
            pvPut(abortCmd);
{block(enter(1), 12)}
        }} state step1
        when (abortCmd) {{
            abortCmd = 0;
            pvPut(abortCmd);
        }} state idle
    }}

{(chr(10) + chr(10)).join(states)}

{(chr(10) + chr(10)).join(finals)}
}}
"""


